#!/usr/bin/env python3
"""Extracts the colour palettes of pl-box (crates/pl-core/src/color.rs,
PALETTES, names from the comments above each) and biome (palettes.js,
names from the trailing comments) into src/palettes_data.S: one name and
a list of 0xRRGGBB words per palette. Identical colour lists are kept
once; repeated names get a suffix. Everything else (lifting dark colours,
expansion to K colours, the distinguishability check, picking) is done at
run time in src/palettes.S.
  usage: tools/gen_palettes.py [~/code/pl-box] [~/code/biome] > src/palettes_data.S"""
import os, re, sys

plbox = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/code/pl-box")
biome = sys.argv[2] if len(sys.argv) > 2 else os.path.expanduser("~/code/biome")

def slug(s):
    s = s.lower().replace("&", "and")
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s

pals = []  # (name, source, [ints])
src = open(os.path.join(plbox, "crates/pl-core/src/color.rs")).read()
body = src[src.index("const PALETTES"):src.index("];", src.index("const PALETTES"))]
name = None
for line in body.splitlines():
    t = line.strip()
    if t.startswith("//"):
        c = t.lstrip("/ ").strip()
        if not c.startswith("---"):
            name = c.split("—")[0].split(" - ")[0].strip()
        continue
    if t.startswith("&["):
        cols = []
        name_here = name
        pals.append([name_here, "pl-box", cols])
    for h in re.findall(r'"#([0-9a-fA-F]{6})"', t):
        pals[-1][2].append(int(h, 16))
js = open(os.path.join(biome, "palettes.js")).read()
for m in re.finditer(r"\[([^\[\]]*)\],?\s*//\s*(.+)", js):
    cols = [int(h, 16) for h in re.findall(r"#([0-9a-fA-F]{6})", m.group(1))]
    pals.append([m.group(2).strip(), "biome", cols])

out, seen_cols, seen_names = [], set(), {}
for name, source, cols in pals:
    key = tuple(cols)
    if key in seen_cols:
        continue
    seen_cols.add(key)
    s = slug(name)
    if s in seen_names:
        seen_names[s] += 1
        s = f"{s}-{seen_names[s]}"
    else:
        seen_names[s] = 1
    out.append((s, source, cols))

print("/* Generated by tools/gen_palettes.py from pl-box color.rs (PALETTES) and */")
print("/* biome palettes.js. Do not edit; rerun the script. */")
print("        .section .rodata")
for i, (s, source, cols) in enumerate(out):
    print(f'pn{i:03d}: .asciz "{s}"')
print("        .balign 4")
print("        .globl pl_palette_data")
print("pl_palette_data:                /* per palette: count, then 0xRRGGBB words */")
for i, (s, source, cols) in enumerate(out):
    print(f"pd{i:03d}:  .long {len(cols)}  /* {s} ({source}) */")
    for j in range(0, len(cols), 6):
        print("        .long " + ", ".join(f"0x{c:06x}" for c in cols[j:j + 6]))
print('        .section .data.rel.ro, "aw"')
print("        .balign 8")
print("        .globl pl_palette_names, pl_palette_cols, pl_npalettes")
print("pl_palette_names:")
for i in range(len(out)):
    print(f"        .quad pn{i:03d}")
print("pl_palette_cols:")
for i in range(len(out)):
    print(f"        .quad pd{i:03d}")
print("        .section .rodata")
print(f"pl_npalettes: .long {len(out)}")
print(f".set NPALETTES_GEN, {len(out)}", file=sys.stderr)
